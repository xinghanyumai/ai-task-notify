# ---------------------------------------------------------------- 描边

# 每个语义一个值，不许混用。
#   rule      分隔线（卡片内分行的细线、列表分隔）
#   control   控件描边（按钮、输入框、开关轨道、复选框）
#   ring      焦点环
#   icon      图标笔画默认值；icon_thin 给 16px 的小图标（再粗就糊）；
#             icon_bold 给需要强调的单笔图标（勾选的对勾）
_STROKE = {
    "rule": 1,
    "control": 1,
    "ring": 2,
    "icon": 1.8,
    "icon_thin": 1.6,
    "icon_bold": 2,
}


class _Stroke:
    def __getattr__(self, name: str) -> int:
        try:
            return theme.S(_STROKE[name])
        except KeyError:
            raise AttributeError(f"没有这个描边令牌：{name}") from None


STK = _Stroke()


# ---------------------------------------------------------------- 动效


class MOTION:
    """三档时长，一个帧间隔。

    缓动不在这里定义，直接用 `anim` 里的函数，对应关系固定：

    - `ease_out_expo`  进场、位移这类「从静止到静止」的动作。它前段极快、
                        后段极慢，是这一版手感变好的主要来源：上一版统一用
                        ease_out_cubic，中段速度不够快，看起来像「推着走」。
    - `ease_out_cubic` 颜色、透明度、边框这类「只变数值」的过渡。
    - `ease_out_back`  开关滑块，唯一有物理感的地方，末端轻微过冲。

    三档时长：

    - quick  90ms   悬停、按下、焦点环——手指还按着时的反馈，必须「跟手」
    - base   160ms  状态切换、卡片进场、内容替换
    - slow   240ms  一次性大位移（导航指示条滑动、折叠面板展开）

    任何一处偏离这三档，注释里必须写清为什么。上一版有 120/130/150/170/180/
    200/240/260 八个时长，其中 130 和 120 是同一个意思的两种写法。
    """

    quick = 90
    base = 160
    slow = 240

    # 启动层专用三档。它们不在「90/160/240」这套里，因为启动层是全应用
    # 唯一可以「炫」的地方：用户只在这里停留 1–2 秒，看过就没了，
    # 不会造成长期视觉疲劳（P1 第 5.4 节）。
    splash_in = 220     # 启动层整层 alpha 0.3→1.0
    splash_out = 300    # 启动层淡出。这是「不许超过 300ms」的唯一例外
    progress = 400      # 进度线推进一格（每建完一页）

    interval = 16   # 约 62fps。13ms 是 77fps，屏幕刷新跟不上，白烧 CPU
    stagger = 24    # 卡片依次进场的间隔，5 张卡片总共多花 96ms
